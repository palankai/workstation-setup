import os
import subprocess
import sys
from pathlib import Path

import pytest

from workstation_manager.core import Workspace

from .test_cli import ws
from .test_core import workspace  # noqa: F401

GENERATE = """
from workstation_manager.generator import app_file, combine, profile_file

combine("{out}/a.md", app_file("shared.md"), profile_file("part.md", optional=True))
combine("{out}/b.conf", app_file("shared.md"), profile_file("missing.md"))
combine("{out}/c.md", app_file("shared.md"))
combine("{out}/d.md", app_file("none.md", optional=True))
"""


@pytest.fixture
def generating(workspace: Workspace, tmp_path, monkeypatch):  # noqa: F811
    monkeypatch.setenv("XDG_STATE_HOME", str(tmp_path / "state"))
    app = workspace.catalog().get("jq").path
    out = tmp_path / "out"
    (app / "shared.md").write_text("# Shared\n\nBritish English.\n")
    (app / "30-generate.py").write_text(GENERATE.format(out=out))
    part = workspace.root / "sensitive" / "targets" / "dev"
    part.mkdir(parents=True)
    (part / "part.md").write_text("Personal bit.\n")
    return workspace, out


def generate(workspace: Workspace, *args: str) -> int:  # noqa: F811
    with pytest.raises(SystemExit) as exit:
        ws(workspace, "generate", "--profile", "dev", *args)
    return exit.value.code


def test_generate_writes_combined_files_and_fails_on_missing_source(generating, capsys):
    workspace, out = generating
    assert generate(workspace) == 1  # b.conf's required source is missing
    output = capsys.readouterr().out
    assert "Report: file://" in output
    a = (out / "a.md").read_text()
    header, _, body = a.partition("\n")
    assert header.startswith("<!-- Generated by `ws generate` from applications/jq/shared.md, ")
    assert "sensitive/targets/dev/part.md" in header and header.endswith(" -->")
    assert body == "# Shared\n\nBritish English.\n\nPersonal bit.\n"
    assert not (out / "b.conf").exists()
    assert (out / "c.md").is_file()  # a failure doesn't stop the step's other files
    assert not (out / "d.md").exists()  # every source optional and missing
    assert "out/d.md: skipped, no sources" in output


def test_generate_refuses_edited_files_unless_overwrite(generating, capsys):
    workspace, out = generating
    script = GENERATE.format(out=out).splitlines(keepends=True)
    without_b = "".join(line for line in script if "b.conf" not in line)
    (workspace.catalog().get("jq").path / "30-generate.py").write_text(without_b)
    assert generate(workspace) == 0
    a = out / "a.md"
    first = a.read_text()
    assert generate(workspace) == 0
    assert a.read_text() == first

    a.write_text(first + "my edit\n")
    (out / "c.md").write_text("hand-written\n")
    assert generate(workspace, "-n") == 1
    assert a.read_text().endswith("my edit\n")
    capsys.readouterr()

    assert generate(workspace) == 1
    report = capsys.readouterr().out
    assert "edited since generated; refused" in report and "not generated (no header)" in report

    assert generate(workspace, "--overwrite") == 0
    assert a.read_text() == first
    assert (out / "a.md.bak").read_text().endswith("my edit\n")
    assert (out / "c.md.bak").read_text() == "hand-written\n"


def test_symlink_is_refused(generating, tmp_path):
    workspace, out = generating
    out.mkdir()
    (tmp_path / "elsewhere.md").write_text("x\n")
    (out / "c.md").symlink_to(tmp_path / "elsewhere.md")
    env = {
        **os.environ,
        "APP_DIR": str(workspace.catalog().get("jq").path),
        "WORKSTATION_PROFILE": "dev",
        "WORKSTATION_ROOT": str(workspace.root),
    }
    script = "from workstation_manager.generator import app_file, combine\n"
    script += f'combine("{out}/c.md", app_file("shared.md"))\n'
    result = subprocess.run([sys.executable, "-c", script], env=env, capture_output=True, text=True)
    assert result.returncode == 1 and "a symlink; refused" in result.stderr
    assert (out / "c.md").is_symlink()


def test_update_runs_generate_steps_and_plan_lists_them(generating, capsys):
    workspace, out = generating
    with pytest.raises(SystemExit):
        ws(workspace, "update", "--no-brew", "--profile", "dev", "jq")
    assert (out / "a.md").is_file()
    with pytest.raises(SystemExit, match="0"):
        ws(workspace, "plan", "--profile", "dev", "jq")
    assert "30-generate.py   generate" in capsys.readouterr().out
