"""Scaffold uninstall steps for applications installed by Brewfiles alone.

An application qualifies when its only steps are Brewfiles holding `brew`, `cask` and `tap`
lines. It gets `UNINSTALL_FILE`, which uninstalls its formulae and casks if they're installed
(uninstall steps run on every update until cleared, so they must be idempotent). Taps stay.

A file starting with `MARKER` is regenerated; one without it is hand-written and left alone.
Packages another application's Brewfile also installs are left out.
"""

import re
import shlex
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

from .core.catalog import Application, Catalog

UNINSTALL_FILE = "90-uninstall.sh"
MARKER = "# Generated by `ws scaffold-uninstall`"
BREWFILE_LINE = re.compile(r'^(\w+)\s+"([^"]+)"')
SUPPORTED = {"brew", "cask", "tap"}


@dataclass(frozen=True)
class Package:
    kind: str  # brew, cask or tap
    name: str


def scaffold_uninstall(catalog: Catalog, ids: list[str], dry_run: bool) -> list[str]:
    applications = [catalog.get(id) for id in ids] if ids else list(catalog)
    owners = package_owners(catalog)
    lines = []
    for application in applications:
        if line := generate_for(application, owners, dry_run):
            lines.append(line)
    return lines


def generate_for(application: Application, owners: dict[Package, set[str]], dry_run: bool) -> str | None:
    """What happened to the application, or None when there was nothing to do."""
    target = application.path / UNINSTALL_FILE
    if any(s.kind == "uninstall" and not is_generated(application.path / s.file) for s in application.steps):
        return None
    if any(s.kind in ("run", "once") for s in application.steps):
        return None
    brewfiles = [s.file for s in application.steps if s.kind == "brewfile"]
    if not brewfiles:
        return None
    try:
        packages = [p for f in brewfiles for p in read_brewfile(application.path / f)]
    except ValueError as e:
        return f"{application.id}: skipped, {e}"
    removable = [p for p in dict.fromkeys(packages) if p.kind != "tap"]
    shared = [p for p in removable if owners[p] - {application.id}]
    removable = [p for p in removable if p not in shared]
    if not removable:
        return f"{application.id}: skipped, nothing to uninstall" if packages else None

    content = render(brewfiles, removable, shared, owners, application.id)
    if target.exists() and target.read_text() == content:
        return None
    verb = "update" if target.exists() else "create"
    if not dry_run:
        target.write_text(content)
    return f"{application.id}: {verb} {UNINSTALL_FILE}" + (" (dry run)" if dry_run else "")


def read_brewfile(path: Path) -> list[Package]:
    packages = []
    for raw in path.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        match = BREWFILE_LINE.match(line)
        if not match or match.group(1) not in SUPPORTED:
            raise ValueError(f"unsupported Brewfile line in {path.name}: {line}")
        packages.append(Package(match.group(1), match.group(2)))
    return packages


def package_owners(catalog: Catalog) -> dict[Package, set[str]]:
    owners: dict[Package, set[str]] = defaultdict(set)
    for application in catalog:
        for step in application.steps:
            if step.kind != "brewfile":
                continue
            try:
                for package in read_brewfile(application.path / step.file):
                    owners[package].add(application.id)
            except ValueError:
                continue  # such lines can't be uninstalled here anyway
    return owners


def render(
    brewfiles: list[str], packages: list[Package], shared: list[Package], owners: dict[Package, set[str]], id: str
) -> str:
    lines = [f"{MARKER} from {', '.join(brewfiles)}; remove this line to edit by hand"]
    for package in shared:
        others = ", ".join(sorted(owners[package] - {id}))
        lines.append(f"# {package.kind} {package.name} left out: also installed by {others}")
    # Reverse Brewfile order, so later packages (often built on earlier ones) go first
    for package in reversed(packages):
        flag = "--formula" if package.kind == "brew" else "--cask"
        name = shlex.quote(package.name)
        lines.append(f"if brew list {flag} {name} >/dev/null 2>&1; then brew uninstall {flag} {name}; fi")
    return "\n".join(lines) + "\n"


def is_generated(path: Path) -> bool:
    with path.open() as f:
        return f.readline().startswith(MARKER)
