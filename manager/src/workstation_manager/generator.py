"""For application `*generate.py` steps: files on this machine built from the repository.

A generate step only declares what to write, for example

    from workstation_manager.generator import app_file, combine, profile_file

    combine("~/.claude/CLAUDE.md", app_file("instructions/user.md"),
            profile_file("instructions/user.md", optional=True))

and the writing happens here, so every step behaves the same:

- A generated file starts with a header naming its sources and the sha256 of the rest.
- It's rewritten only while that hash matches. A file edited since, a file without the
  header (hand-written) and a symlink are refused, unless `ws generate --overwrite`,
  which keeps the previous file as `<name>.bak`.
- `ws generate -n` only says what would happen.

A refusal or a missing source doesn't stop the step's other files; the step fails at the end.
"""

import atexit
import hashlib
import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path

from .helpers import app_dir, repo_root

# Set by `ws generate`
DRY_RUN = "WS_GENERATE_DRY_RUN"
OVERWRITE = "WS_GENERATE_OVERWRITE"

HEADER = re.compile(r"^(<!--|#) Generated by `ws generate` .* sha256:([0-9a-f]{64})( -->)?$")


@dataclass(frozen=True)
class Source:
    path: Path
    # A missing optional source is left out; a missing required one fails the file
    optional: bool = False


def profile() -> str:
    return os.environ["WORKSTATION_PROFILE"]


def app_file(path: str, optional: bool = False) -> Source:
    """A file in the application's folder."""
    return Source(app_dir() / path, optional)


def profile_file(path: str, optional: bool = False) -> Source:
    """A file in this profile's part of the private repository: sensitive/targets/<profile>/."""
    return Source(repo_root() / "sensitive" / "targets" / profile() / path, optional)


def combine(output: str | Path, *sources: Source | str | Path) -> bool:
    """Writes the sources' text one after the other, separated by a blank line.
    Returns whether the file is now as generated."""
    target = Path(output).expanduser()
    parts = [s if isinstance(s, Source) else Source(Path(s)) for s in sources]
    if missing := [str(s.path) for s in parts if not s.optional and not s.path.is_file()]:
        return _fail(target, f"missing source {', '.join(missing)}")
    texts = [s.path.read_text().strip("\n") for s in parts if s.path.is_file()]
    body = "\n\n".join(t for t in texts if t) + "\n"
    used = [_shown(s.path) for s in parts if s.path.is_file()]
    return _write(target, _header(target, used, body) + "\n" + body)


def _header(target: Path, sources: list[str], body: str) -> str:
    digest = hashlib.sha256(body.encode()).hexdigest()
    text = f"Generated by `ws generate` from {', '.join(sources)}; edit those, not this file. sha256:{digest}"
    return f"<!-- {text} -->" if target.suffix in (".md", ".html") else f"# {text}"


def _write(target: Path, content: str) -> bool:
    dry_run = bool(os.environ.get(DRY_RUN))
    if target.is_symlink() or target.exists():
        current = None if target.is_symlink() else target.read_text()
        if current == content:
            return _say(target, "unchanged")
        problem = _edited(current)
        if problem and not os.environ.get(OVERWRITE):
            return _fail(target, f"{problem}; refused (ws generate --overwrite replaces it, keeping a .bak)")
        if problem and not dry_run:
            backup = target.with_name(target.name + ".bak")
            os.replace(target, backup)
            print(f"{_shown(target)}: kept the previous file as {backup.name}")
    if dry_run:
        return _say(target, "would write")
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_name(f".{target.name}.tmp")
    temporary.write_text(content)
    os.replace(temporary, target)
    return _say(target, "written")


def _edited(current: str | None) -> str | None:
    """Why the file isn't ours to rewrite, or None."""
    if current is None:
        return "a symlink"
    first, _, rest = current.partition("\n")
    match = HEADER.match(first)
    if not match:
        return "not generated (no header)"
    if hashlib.sha256(rest.encode()).hexdigest() != match.group(2):
        return "edited since generated"
    return None


def _shown(path: Path) -> str:
    """Repository files relative to the repository, others with ~ for home."""
    for base, prefix in ((repo_root(), ""), (Path.home(), "~/")):
        if path.is_relative_to(base):
            return prefix + str(path.relative_to(base))
    return str(path)


def _say(target: Path, what: str) -> bool:
    print(f"{_shown(target)}: {what}")
    return True


_failures = 0


def _fail(target: Path, why: str) -> bool:
    global _failures
    if not _failures:
        atexit.register(_exit_failed)
    _failures += 1
    print(f"{_shown(target)}: {why}", file=sys.stderr)
    return False


def _exit_failed() -> None:
    # atexit can't change the exit status any other way
    sys.stdout.flush()
    sys.stderr.flush()
    os._exit(1)
